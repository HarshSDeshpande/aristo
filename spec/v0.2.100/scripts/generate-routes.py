#!/usr/bin/env python3
"""Render routes/registry.yaml into every consumer's file (T0 "names once"). Run it through
scripts/generate-routes.sh, which formats the Rust with the pinned rustfmt.

    generate-routes.py --registry routes/registry.yaml --out generated --retire-list routes/RETIRE-LIST.md
    generate-routes.py --registry <registry.yaml> --conductor <conductor checkout>

The first form writes every output under the spec repo; the second only the conductor's two Rust
files, in place, so the conductor's CI can regenerate them from its vendored copy and fail on drift.
Every word is checked against the closed vocabularies of scripts/validate.py: an unknown word stops
the generator.
"""
import argparse, json, os, sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from registry_vocab import (AT, CAPS, CHECKS_UNIT, MACHINE, READS, RUNGS)  # noqa: E402

HEADER_RS = ('// @generated by aretta-conductor-spec scripts/generate-routes.sh from routes/registry.yaml.\n'
             '// Do not edit: change the registry and regenerate.\n')

AT_RS = {'repo': 'Repo', 'org_level': 'OrgLevel', 'org_directory': 'OrgDirectory', 'org_root': 'OrgRoot',
         'admin': 'Admin', 'sign_in': 'SignIn'}
RUNG_RS = {r: r.capitalize() for r in RUNGS}
READS_RS = {r: r.capitalize() for r in READS}
CAP_RS = {'read': 'Read', 'verify': 'Verify', 'steer': 'Steer', 'campaign_author': 'CampaignAuthor',
          'formalize': 'Formalize', 'operate': 'Operate', 'stamp': 'Stamp'}
CHECK_RS = {'person_only': 'PersonOnly', 'repo_admin_bit': 'RepoAdminBit', 'write_door': 'WriteDoor',
            'admin_is_write_door': 'AdminIsWriteDoor', 'target_write_door': 'TargetWriteDoor',
            'org_image_door': 'OrgImageDoor', 'admin_or_staff': 'AdminOrStaff'}
assert set(AT_RS) == set(AT) and set(CAP_RS) == set(CAPS) and set(CHECK_RS) == set(CHECKS_UNIT)
assert set(MACHINE) == set(CAPS) | {'none'}


def caps_rs(words):
    caps = words.split('+')
    for c in caps:
        if c not in CAP_RS:
            raise SystemExit(f'unknown capability {c!r}')
    return '&[' + ', '.join(f'Capability::{CAP_RS[c]}' for c in caps) + ']'


def check_rs(word):
    if word.startswith('cap:'):
        return f'Check::Cap(Capability::{CAP_RS[word[4:]]})'
    if word.startswith('any_cap:'):
        return f'Check::AnyCap({caps_rs(word[8:])})'
    return f'Check::{CHECK_RS[word]}'


def machine_rs(word):
    """The machine column (T2): `None` (no machine passes) or `Some(<the one capability>)`."""
    if word not in MACHINE:
        raise SystemExit(f'unknown machine word {word!r}')
    return 'None' if word == 'none' else f'Some(Capability::{CAP_RS[word]})'


def rust_str(s):
    return json.dumps(s)  # a JSON string literal is a valid Rust string literal for these paths


def doors_rs(rows):
    out = [HEADER_RS,
           '//! THE DOOR TABLE\'s rows (`crate::doors::DOORS`): one per registry row that is a door (it has\n'
           '//! an `at`), in the registry\'s order. The words are the registry\'s; the types are\n'
           '//! `crate::doors`\'s.\n\n',
           'use crate::doors::{At, Check, Door, Reads, Requires};\n',
           'use crate::facts::Capability;\n\n',
           'pub const DOORS: &[Door] = &[\n']
    for r in rows:
        if 'at' not in r:
            continue
        p = r['person']
        out.append(
            f'    // {r["id"]}\n'
            f'    Door {{ method: {rust_str(r["method"])}, path: {rust_str(r["path"])}, '
            f'at: At::{AT_RS[r["at"]]}, requires: Requires::{RUNG_RS[p["rung"]]}, '
            f'people: &[{", ".join(check_rs(c) for c in p.get("checks") or [])}], '
            f'machine: {machine_rs(r["machine"])}, reads: Reads::{READS_RS[r["reads"]]}, '
            f'release2: {str(bool(r.get("release2"))).lower()}, '
            f'org_level: {str(bool(r.get("org_level"))).lower()} }},\n')
    out.append('];\n')
    return ''.join(out)


def routes_rs(rows):
    out = [HEADER_RS,
           '//! THE ROUTE LIST: every route the conductor mounts, by its registry id, in the registry\'s\n'
           '//! order. `crate::handlers` binds each id to its handler; nothing else names a path.\n\n',
           '/// One mounted route.\n',
           '#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n',
           'pub struct Route {\n',
           '    /// The stable name (`family.noun.verb`), never renamed.\n',
           '    pub id: &\'static str,\n',
           '    pub method: &\'static str,\n',
           '    /// The axum template.\n',
           '    pub path: &\'static str,\n',
           '}\n\n',
           'pub const ROUTES: &[Route] = &[\n']
    for r in rows:
        out.append(f'    Route {{ id: {rust_str(r["id"])}, method: {rust_str(r["method"])}, '
                   f'path: {rust_str(r["path"])} }},\n')
    out.append('];\n')
    return ''.join(out)


def const_name(route_id):
    return route_id.upper().replace('.', '_').replace('@', '_AT_')


def cli_paths_rs(rows):
    out = [HEADER_RS,
           '//! The conductor routes the CLI calls (registry `callers: cli`), by id. A path is the\n'
           '//! conductor\'s axum template: `:repo` is the registry name of the repo.\n\n',
           '/// One conductor route.\n',
           '#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n',
           'pub struct Route {\n',
           '    pub id: &\'static str,\n',
           '    pub method: &\'static str,\n',
           '    pub path: &\'static str,\n',
           '}\n']
    for r in rows:
        if 'cli' in (r.get('callers') or []):
            out.append(f'\npub const {const_name(r["id"])}: Route = Route {{ id: {rust_str(r["id"])}, '
                       f'method: {rust_str(r["method"])}, path: {rust_str(r["path"])} }};\n')
    return ''.join(out)


def dashboard_json(rows):
    """The dashboard registry's shape (contract/routes.json): the client's prefix family is derived
    from the path, the `requires` word is the person rung (null for a row with no door)."""
    out = []
    for r in rows:
        if 'page' not in (r.get('callers') or []):
            continue
        path = r['path']
        if path.startswith('/:repo/api/'):
            fam, tmpl = 'repo-api', path[len('/:repo/api'):]
        elif path.startswith('/api/'):
            fam, tmpl = 'org-api', path[len('/api'):]
        else:
            fam, tmpl = 'origin', path
        out.append({'id': r['id'], 'method': r['method'], 'family': fam, 'path_template': tmpl,
                    'requires': r['person']['rung'] if 'person' in r else None, 'deferred': None})
    return json.dumps(out, indent=2) + '\n'


def plugin_toml(rows):
    out = ['# @generated by aretta-conductor-spec scripts/generate-routes.sh from routes/registry.yaml.\n',
           '# Do not edit. The conductor routes the FDE seat calls (registry `callers: seat`).\n']
    for r in rows:
        if 'seat' in (r.get('callers') or []):
            out.append(f'\n[[route]]\nid = {json.dumps(r["id"])}\nmethod = {json.dumps(r["method"])}\n'
                       f'path = {json.dumps(r["path"])}\n')
    return ''.join(out)


def openapi_path(path):
    """`/admin/orgs/:org/x` → `/admin/orgs/{org}/x` (the spec's spelling)."""
    return '/'.join('{' + s[1:] + '}' if s and s[0] in ':*' else s for s in path.split('/'))


RETIRE_MARK = ('<!-- GENERATED below this line by scripts/generate-routes.sh from routes/registry.yaml '
               '(the `retired` column); do not edit. -->\n')


def retire_table(rows):
    by_id = {r['id']: r for r in rows}
    out = [RETIRE_MARK, '\n## The retired routes\n\n',
           f'{sum("retired" in r for r in rows)} rows, in the registry\'s order.\n\n',
           '| Route | Answers | Successor | id |\n', '|---|---|---|---|\n']
    for r in rows:
        ret = r.get('retired')
        if not ret:
            continue
        succ = ret.get('successor')
        s = 'none' if succ is None else f'`{by_id[succ]["method"]} {openapi_path(by_id[succ]["path"])}` ({succ})'
        out.append(f'| `{r["method"]} {openapi_path(r["path"])}` | {ret["status"]} | {s} | {r["id"]} |\n')
    return ''.join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--registry', required=True)
    ap.add_argument('--out')
    ap.add_argument('--retire-list')
    ap.add_argument('--conductor')
    a = ap.parse_args()
    rows = yaml.safe_load(open(a.registry))
    if a.conductor:
        write(f'{a.conductor}/crates/access/src/generated/doors.rs', doors_rs(rows))
        write(f'{a.conductor}/crates/routes/src/generated/routes.rs', routes_rs(rows))
        return
    o = a.out
    write(f'{o}/conductor/crates/access/src/generated/doors.rs', doors_rs(rows))
    write(f'{o}/conductor/crates/routes/src/generated/routes.rs', routes_rs(rows))
    write(f'{o}/dashboard/contract/routes.json', dashboard_json(rows))
    write(f'{o}/cli/crates/aristo-core/src/conductor/paths.rs', cli_paths_rs(rows))
    write(f'{o}/plugin/routes.toml', plugin_toml(rows))
    if a.retire_list:
        text = open(a.retire_list).read()
        preamble = text.split(RETIRE_MARK)[0]
        write(a.retire_list, preamble + retire_table(rows))


if __name__ == '__main__':
    main()
